package part18;

// Create a class called Food
public class Food {

    // Instance variable that stores the food's name
    String name;

    // Constructor for the Food class
    // Runs automatically when a Food object is created
    Food(String name) {

        // Assign the parameter name to the object's name field
        // this.name = object's variable
        // name = parameter passed into the constructor
        this.name = name;
    }

} // End of Food class