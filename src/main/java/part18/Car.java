package part18;

// Create a class called Car
public class Car {

    // Instance variable that stores the car's name
    String name;

    // Constructor for the Car class
    // Runs automatically when a new Car object is created
    Car(String name) {

        // Assign the parameter name to the object's name field
        // this.name = object's variable
        // name = parameter passed into the constructor
        this.name = name;
    }

} // End of Car class
